CREATE TABLE IF NOT EXISTS members (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 name VARCHAR(40) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 session_version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS password_resets (
 token_hash VARCHAR(64) PRIMARY KEY,
 member_id BIGINT NOT NULL,
 expires_at TIMESTAMP NOT NULL,
 FOREIGN KEY (member_id) REFERENCES members(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS plans (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, member_id BIGINT NOT NULL,
 title VARCHAR(100) NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 budget DECIMAL(12,2) NOT NULL DEFAULT 0, description TEXT NOT NULL,
 FOREIGN KEY(member_id) REFERENCES members(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS plan_stops (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, plan_id BIGINT NOT NULL, position INT NOT NULL,
 day_number INT NOT NULL, content_id VARCHAR(20) NOT NULL, title VARCHAR(200) NOT NULL,
 address VARCHAR(500) NOT NULL, latitude DOUBLE NOT NULL, longitude DOUBLE NOT NULL,
 cost DECIMAL(12,2) NOT NULL DEFAULT 0, notes TEXT NOT NULL,
 FOREIGN KEY(plan_id) REFERENCES plans(id) ON DELETE CASCADE
);
